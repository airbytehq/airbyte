-- Smoke coverage for a base table and view.
CREATE OR REPLACE TABLE `${BIGQUERY_PROJECT}.${PROVEFIX_DATASET}.smoke_table` (
  id INT64,
  name STRING,
  updated_at TIMESTAMP
) AS
SELECT 1, 'Ada', TIMESTAMP('2025-01-01 00:00:00+00')
UNION ALL
SELECT 2, 'Grace', TIMESTAMP('2025-01-02 00:00:00+00')
UNION ALL
SELECT 3, 'Linus', TIMESTAMP('2025-01-03 00:00:00+00');

CREATE OR REPLACE VIEW `${BIGQUERY_PROJECT}.${PROVEFIX_DATASET}.smoke_view` AS
SELECT id, name, updated_at
FROM `${BIGQUERY_PROJECT}.${PROVEFIX_DATASET}.smoke_table`;
